import pytest
from django.db import transaction
from arkumu.metadata.models.resource import Resource, ResourceType
from arkumu.common.hash_utils import generate_value_hash, generate_value_hash_and_normalize
from arkumu.common.uri_utils import normalize_string_nfc


@pytest.mark.django_db
def test_single_save_normalization_and_hashing():
    """Test that individual save() normalizes and generates hash correctly."""
    
    # Test with Unicode text that needs normalization
    # Using composed vs decomposed Unicode (é vs e + combining accent)
    original_value = "café"  # This might be decomposed form
    
    # Create resource using individual save (not bulk)
    resource = Resource(
        resource_type=ResourceType.LITERAL,
        value=original_value,
        datatype="xsd:string",
        language="de"
        # Note: No value_hash set - should be generated by save()
    )
    
    # Verify hash is not set before save
    assert resource.value_hash is None
    
    # Save the resource
    resource.save()
    
    # Verify value was normalized
    expected_normalized = normalize_string_nfc(original_value)
    assert resource.value == expected_normalized
    
    # Verify hash was generated by save() as fallback for individual saves
    assert resource.value_hash is not None
    assert len(resource.value_hash) == 64  # BLAKE2B 32-byte = 64 hex chars
    
    # Verify hash matches what centralized function would generate
    expected_hash = generate_value_hash(original_value)
    assert resource.value_hash == expected_hash


@pytest.mark.django_db  
def test_bulk_create_normalization_and_hashing():
    """Test that bulk_create properly normalizes and hashes values."""
    
    # Test values with Unicode normalization needs
    test_values = [
        "café",      # Might need normalization
        "résumé",    # Might need normalization  
        "naïve",     # Might need normalization
        "Hello World"  # Simple ASCII
    ]
    
    resources_to_create = []
    expected_hashes = []
    expected_normalized = []
    
    for value in test_values:
        # Use the efficient hash and normalize function
        value_hash, normalized_value = generate_value_hash_and_normalize(value)
        
        resource = Resource(
            value=normalized_value,
            value_hash=value_hash,
            resource_type=ResourceType.LITERAL,
            name=normalized_value[:100] if len(normalized_value) > 100 else normalized_value,
            datatype="http://www.w3.org/2001/XMLSchema#string",
            language="de",
            organization=None
        )
        
        resources_to_create.append(resource)
        expected_hashes.append(value_hash)
        expected_normalized.append(normalized_value)
    
    # Bulk create
    Resource.objects.bulk_create(resources_to_create)
    
    # Verify all resources were created with correct normalization and hashing
    created_resources = Resource.objects.filter(
        resource_type=ResourceType.LITERAL,
        language="de"
    )
    
    assert created_resources.count() == len(test_values)
    
    # Check each resource by finding it by hash (more reliable than ordering)
    for i, (original_value, expected_hash, expected_norm) in enumerate(zip(test_values, expected_hashes, expected_normalized)):
        resource = created_resources.get(value_hash=expected_hash)
        
        # Value should be normalized
        assert resource.value == expected_norm
        
        # Hash should be set correctly  
        assert resource.value_hash == expected_hash
        
        # Verify hash matches what we'd get from the centralized function
        assert resource.value_hash == generate_value_hash(original_value)


